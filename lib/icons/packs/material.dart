FontGlyph _m(
  IconPack style,
  IconData outlined,
  IconData rounded,
  IconData sharp,
) => FontGlyph(_pick(style, outlined, rounded, sharp));

FontGlyph _filled(
  IconPack style,
  IconData outlined,
  IconData rounded,
  IconData sharp,
) => FontGlyph(_pick(style, outlined, rounded, sharp), fill: 1);

IconData _pick(
  IconPack style,
  IconData outlined,
  IconData rounded,
  IconData sharp,
) => switch (style) {
  IconPack.materialRounded => rounded,
  IconPack.materialSharp => sharp,
  _ => outlined,
};
