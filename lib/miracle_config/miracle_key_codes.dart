// The evdev key codes miracle's key bindings are written in.
//
// `CustomKeyCommand.key` and `KeyCommandOverride.key` are raw Linux input event
// codes — `KEY_R` is 19 — so a binding editor that did not carry this table
// would be a numeric field asking the user to know `input-event-codes.h` by
// heart.
//
// Generated from `/usr/include/linux/input-event-codes.h` and then frozen: it is
// a kernel UAPI header, so a code that exists never changes meaning, and reading
// the host's copy at run time would make the same configuration render
// differently on two machines. Aliases (several spellings of one code) collapse
// to the first spelling the header gives, so the list is one row per code.
//
// Deliberately Flutter-free, like `input_trigger/keysym.dart`, so the lookups
// are a plain unit test.
library;

/// One key the compositor can bind, as evdev names it.
class MiracleKey {
  const MiracleKey(this.code, this.name, this.label);

  /// The Linux input event code — what miracle's configuration actually holds.
  final int code;

  /// The `input-event-codes.h` spelling, e.g. `KEY_LEFTBRACE`.
  ///
  /// Shown beside the label rather than instead of it: two keys can read alike
  /// once humanised ("Left bracket ([)" and "Keypad left paren"), and the
  /// header's own name is the unambiguous one to search for.
  final String name;

  /// What a person calls this key, e.g. `Left bracket ([)`.
  final String label;

  @override
  String toString() => 'MiracleKey($code, $name)';
}

