/// The table, indexed for lookup.
///
/// Lazy: a shell whose user never opens the key bindings page builds none of it
/// — `world_cities.dart`'s trick.
final Map<int, MiracleKey> _byCode = {
  for (final key in kMiracleKeys) key.code: key,
};

/// The key [code] names, or null if evdev does not name it.
MiracleKey? miracleKeyForCode(int code) => _byCode[code];

/// A label for [code], falling back to the number itself.
///
/// A binding can perfectly well name a code this table does not — a vendor key
/// on somebody's keyboard, or a configuration written against a newer kernel —
/// and showing it as "Key code 748" keeps that binding editable and, above all,
/// *saveable* as it was authored. The degrade-per-field rule from
/// `config_reader.dart`, applied to somebody else's file.
String miracleKeyLabel(int code) => _byCode[code]?.label ?? 'Key code $code';
