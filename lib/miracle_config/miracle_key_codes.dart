// The xkb keysyms miracle's key bindings are written in.
//
// `CustomKeyCommand.key` and `KeyCommandOverride.key` are keysyms: miracle
// reads `key: XF86AudioRaiseVolume` through `xkb_keysym_from_name`, matches the
// keysym a key press *resolves* to, and writes the value back through
// `xkb_keysym_get_name`. (`package:miracle`'s doc comments still call the field
// an evdev code; the compositor's parser and matcher are what decide.) So a
// binding editor that did not carry this table would be a numeric field asking
// the user to know `xkbcommon-keysyms.h` by heart.
//
// Resolved, not physical: Shift+Q arrives as `Q`, Shift+1 on a US layout as
// `exclam` — which is why the shifted characters are rows of their own, and
// why miracle's defaults bind `Q` with Shift rather than `q`.
//
// Generated from `keysymdef.h` (ASCII, Latin-1 and the function, cursor,
// keypad and modifier block), `XF86keysym.h` (every vendor key, the volume and
// brightness keys among them) and whatever the evdev `pc+us+inet(evdev)` keymap
// puts on a real key, and then frozen: a keysym's value never changes meaning,
// and reading the host's tables at run time would make the same configuration
// render differently on two machines. [MiracleKey.name] is the spelling
// `xkb_keysym_get_name` returns — the one a save writes — so aliases collapse
// to it and the list is one row per keysym.
//
// Deliberately Flutter-free, like `input_trigger/keysym.dart`, so the lookups
// are a plain unit test.
library;

/// One key the compositor can bind, as xkb names it.
class MiracleKey {
  const MiracleKey(this.keysym, this.name, this.label);

  /// The xkb keysym — what miracle's configuration actually holds.
  final int keysym;

  /// The xkb keysym name, e.g. `XF86AudioRaiseVolume` or `bracketleft` — what
  /// miracle's `config.yaml` spells the key as.
  ///
  /// Shown beside the label rather than instead of it: two keys can read alike
  /// once humanised, and this is the name to search for, the one every other
  /// window manager's documentation uses.
  final String name;

  /// What a person calls this key, e.g. `Volume up` or `Left bracket ([)`.
  final String label;

  @override
  String toString() => 'MiracleKey(0x${keysym.toRadixString(16)}, $name)';
}

