/// The table, indexed for lookup.
///
/// Lazy: a shell whose user never opens the key bindings page builds none of it
/// — `world_cities.dart`'s trick.
final Map<int, MiracleKey> _byKeysym = {
  for (final key in kMiracleKeys) key.keysym: key,
};

/// The key [keysym] names, or null if this table does not carry it.
MiracleKey? miracleKeyForKeysym(int keysym) => _byKeysym[keysym];

/// A label for [keysym] as it reads inside a shortcut, falling back to the
/// number itself.
///
/// A shifted letter reads as the letter: the Shift is already in the
/// shortcut's modifiers, and "Action Key + Shift + Q (shifted)" says it twice.
///
/// A binding can perfectly well name a keysym this table does not — a
/// character from another script, a key from a layout this was not generated
/// from — and showing it as "Keysym 0x6c1" keeps that binding editable and,
/// above all, *saveable* as it was authored. The degrade-per-field rule from
/// `config_reader.dart`, applied to somebody else's file.
String miracleKeyLabel(int keysym) {
  if (keysym >= 0x41 && keysym <= 0x5a) return String.fromCharCode(keysym);
  return _byKeysym[keysym]?.label ?? 'Keysym 0x${keysym.toRadixString(16)}';
}
