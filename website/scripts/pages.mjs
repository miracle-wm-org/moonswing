/**
 * The Configuration group of the sidebar. A `split` page's directory is
 * autogenerated, but under an explicit label: Starlight would otherwise name
 * the group after the directory, lower case.
 */
export function configurationSidebar() {
  return [
    { slug: 'configuration' },
    ...PAGES.map((page) =>
      page.split
        ? {
            label: page.title,
            collapsed: true,
            items: [{ autogenerate: { directory: `configuration/${page.slug}` } }],
          }
        : { slug: `configuration/${page.slug}` },
    ),
  ];
}
